"""Write the victims of a world and their closest building into a YAML file in config/.

Usage:

    python3 scripts/generate_victims_yaml.py                    # every world with victims
    python3 scripts/generate_victims_yaml.py disaster_nathan_benderson_park_world.sdf
"""

import argparse
import math
from pathlib import Path
import xml.etree.ElementTree as ET

PACKAGE_DIR = Path(__file__).resolve().parent.parent
WORLDS_DIR = PACKAGE_DIR / 'worlds'
CONFIG_DIR = PACKAGE_DIR / 'config'

VICTIMS = ['rescue_randy', 'rescue_randy_sitting', 'survivor_male', 'survivor_female',
           'standing_person']

# Building footprints in the model frame (xmin, xmax, ymin, ymax), measured from the meshes
BUILDINGS = {
    'apartment': (-10.1, 10.2, -11.1, 11.2),
    'collapsed_fire_station': (-14.0, 14.0, -9.1, 9.2),
    'collapsed_house': (-8.1, 8.1, -6.5, 6.4),
    'collapsed_industrial_building': (-10.7, 12.4, -8.9, 10.8),
    'collapsed_police_station': (-9.8, 9.8, -11.1, 11.1),
    'fast_food': (-14.1, 11.0, -8.3, 8.3),
    'fire_station': (-10.7, 10.8, -5.7, 6.2),
    'gas_station': (-10.3, 10.3, -24.2, 5.8),
    'grocery_store': (-16.3, 16.6, -9.1, 13.0),
    'house_1': (-8.6, 7.9, -6.8, 6.1),
    'house_2': (-5.1, 7.6, -4.1, 5.7),
    'house_3': (-7.1, 6.1, -4.4, 4.3),
    'law_office': (-3.5, 3.6, -3.4, 2.9),
    'osrf_first_office': (-14.1, 12.1, -11.3, 7.0),
    'parking_garage': (-30.2, 30.3, -21.2, 20.3),
    'police_station': (-6.8, 6.8, -9.8, 9.8),
    'post_office': (-5.2, 5.2, -2.2, 5.1),
    'power_plant': (-60.8, 39.4, -47.5, 35.9),
    'salon': (-3.8, 3.8, -3.5, 2.7),
    'school': (-16.5, 16.5, -11.1, 6.4),
    'thrift_shop': (-3.8, 3.8, -3.5, 2.7),
    'water_tower': (-3.1, 3.1, -3.1, 3.1),
}


def read_includes(world_file):
    """Return (world name, [(name, model, pose)]) of the model:// includes of a world."""
    world = ET.parse(world_file).getroot().find('world')
    includes = []
    for include in world.findall('include'):
        uri = include.findtext('uri', '').strip()
        if not uri.startswith('model://'):
            continue
        model = uri[len('model://'):].strip('/')
        name = (include.findtext('name') or model).strip()
        pose = [float(v) for v in (include.findtext('pose') or '0 0 0 0 0 0').split()]
        includes.append((name, model, pose + [0.0] * (6 - len(pose))))
    return world.get('name'), includes


def distance_to_footprint(x, y, building):
    """Distance from a point to the footprint of a building (0 inside)."""
    _, model, (bx, by, _, _, _, byaw) = building
    xmin, xmax, ymin, ymax = BUILDINGS[model]
    dx, dy = x - bx, y - by
    lx = dx * math.cos(byaw) + dy * math.sin(byaw)
    ly = -dx * math.sin(byaw) + dy * math.cos(byaw)
    return math.hypot(max(xmin - lx, 0.0, lx - xmax), max(ymin - ly, 0.0, ly - ymax))


def name_key(name):
    base, _, index = name.rpartition('_')
    return (base, int(index)) if index.isdigit() else (name, 1)


def write_yaml(world_name, victims, buildings, output):
    lines = [
        f'# Victims placed in the world {world_name} (generated by scripts/{Path(__file__).name})',
        '# Poses are in the world frame: x, y, z in meters and yaw in radians.',
    ]
    if buildings:
        lines += [
            '# near_building is the closest building and distance_to_building its distance (m)',
            '# from the building footprint.',
        ]
    lines += [
        f'world: {world_name}',
        f'count: {len(victims)}',
        'victims:',
    ]
    for name, model, (x, y, z, _, _, yaw) in victims:
        lines += [
            f'  - name: {name}',
            f'    model: {model}',
            f'    pose: {{x: {x:g}, y: {y:g}, z: {z:g}, yaw: {yaw:g}}}',
        ]
        if buildings:
            near = min(buildings, key=lambda b: distance_to_footprint(x, y, b))
            lines += [
                f'    near_building: {near[0]}',
                f'    distance_to_building: {distance_to_footprint(x, y, near):.1f}',
            ]
    output.write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('worlds', nargs='*',
                        help='world files in worlds/ (default: every world with victims)')
    args = parser.parse_args()

    world_files = ([WORLDS_DIR / w for w in args.worlds] if args.worlds
                   else sorted(WORLDS_DIR.glob('*.sdf')))
    CONFIG_DIR.mkdir(exist_ok=True)
    for world_file in world_files:
        world_name, includes = read_includes(world_file)
        victims = sorted((i for i in includes if i[1] in VICTIMS),
                         key=lambda i: (VICTIMS.index(i[1]), name_key(i[0])))
        if not victims:
            continue
        buildings = [i for i in includes if i[1] in BUILDINGS]
        output = CONFIG_DIR / f'{world_name}_victims.yaml'
        write_yaml(world_name, victims, buildings, output)
        print(f'{output.relative_to(PACKAGE_DIR)}: {len(victims)} victims')


if __name__ == '__main__':
    main()
